#!/usr/bin/env node
// Builds the gentle-pi API's runtime (runtime-t3/) from lib/, the way
// build-runtime-modules.mjs builds runtime/: types stripped, `.ts` imports
// rewritten to `.mjs`. The API and the libraries it loads live in their own
// directory so upstream's generator, verifier, and runtime/ stay untouched and
// syncing upstream never conflicts on them.
//
// Usage: node scripts/t3-build-api.mjs --write|--check

import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { stripTypeScriptTypes } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const output = join(root, "runtime-t3");
// The API, then everything it imports from lib/.
const sources = [
	"gentle-pi-api",
	"profile-operations",
	"model-routing",
	"model-routing-authority",
	"agent-profiles",
	"agent-profile-pin",
	"profiles-orchestrator",
	"agent-assets",
	"agent-home",
	"session-worktree-registry",
	"command-rules",
	"destructive-command-guard",
];
const header = "// Generated by scripts/t3-build-api.mjs. Do not edit.\n";

async function generated(name) {
	const source = await readFile(join(root, "lib", `${name}.ts`), "utf8");
	const javascript = stripTypeScriptTypes(source, { mode: "strip" })
		.replace(/\.ts(["'])/g, ".mjs$1")
		.replace(/[ \t]+$/gm, "")
		.replace(/\s+$/u, "");
	for (const [, imported] of javascript.matchAll(/from "\.\/([^"]+)\.mjs"/g)) {
		if (!sources.includes(imported)) throw new Error(`lib/${name}.ts imports ${imported}, which is not built into runtime-t3/`);
	}
	return `${header}${javascript}\n`;
}

async function main() {
	const mode = process.argv[2];
	if (mode !== "--write" && mode !== "--check") throw new Error("usage: t3-build-api.mjs --write|--check");
	const expected = new Map();
	for (const name of sources) expected.set(`${name}.mjs`, await generated(name));
	if (mode === "--write") {
		await rm(output, { recursive: true, force: true });
		await mkdir(output, { recursive: true });
		for (const [file, bytes] of expected) await writeFile(join(output, file), bytes, "utf8");
		process.stdout.write(`runtime-t3 generated (${expected.size} modules)\n`);
		return;
	}
	const present = await readdir(output).catch(() => []);
	const drift = [];
	for (const file of new Set([...present, ...expected.keys()])) {
		const bytes = expected.get(file);
		if (bytes === undefined || !present.includes(file) || (await readFile(join(output, file), "utf8")) !== bytes) {
			drift.push(file);
		}
	}
	if (drift.length > 0) throw new Error(`runtime-t3 is stale: ${drift.join(", ")}; run node scripts/t3-build-api.mjs --write`);
	process.stdout.write(`runtime-t3 matches lib/ (${expected.size} modules)\n`);
}

main().catch((error) => {
	process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
	process.exitCode = 1;
});
